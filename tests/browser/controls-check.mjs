// Uses the existing real browser harness, with a configurable Playwright module.
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
const { chromium } = await import(process.env.APEX_BITE_PLAYWRIGHT_MODULE ?? "playwright");
const outputDirectory = process.env.APEX_BITE_CONTROLS_EVIDENCE ?? join(tmpdir(), "apex-bite-controls-evidence");
await mkdir(outputDirectory, { recursive: true });
const baseUrl = process.env.APEX_BITE_TEST_URL ?? "http://127.0.0.1:5195";
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`${baseUrl}/tests/browser/controls.html`);
  await page.waitForFunction(() => window.controlsHarness);
  const step = (ticks, analog = {}) => page.evaluate((args) => window.controlsHarness.step(args.ticks, args.analog), { ticks, analog });
  const open = () => page.locator("#hud-btn-camera-settings").click();
  const close = async () => {
    await page.locator('#hud-camera-dialog button[type="submit"]').click();
    await page.waitForFunction(() => !document.querySelector("dialog[open]") && document.activeElement === document.body);
  };
  const bind = async (action, key) => {
    await page.locator(`#hud-bind-${action}`).click();
    await page.keyboard.press(key);
  };
  const checks = [];
  const record = (name, condition) => {
    assert(condition, name);
    checks.push(name);
  };
  await open();
  record("Brake/Reverse remapping is visible", await page.locator("#hud-bind-brake").count() === 1);
  await bind("brake", "KeyF");
  record("F replaces Brake/Reverse aliases", await page.locator("#hud-bind-brake").textContent() === "F");
  await close();
  await page.keyboard.down("KeyF");
  const braking = await step(1);
  await page.keyboard.up("KeyF");
  record("Remapped F is progressive through Session", braking.kart.brakeInput > 0 && braking.kart.brakeInput < 0.1);
  record("Hint follows F", (await page.locator("#hud-driving-hint").textContent()).includes("Brake/Reverse: F"));
  await open();
  await bind("brake", "KeyW");
  record("Conflict reports current owner", (await page.locator("#hud-binding-status").textContent()).includes("already belongs to Accelerator"));
  record("Conflict retains F", await page.locator("#hud-bind-brake").textContent() === "F");
  await page.keyboard.press("KeyR");
  record("Shortcut binding is rejected", (await page.locator("#hud-binding-status").textContent()).includes("reserved"));
  await page.keyboard.press("F1");
  record("Unsupported key is rejected", (await page.locator("#hud-binding-status").textContent()).includes("Choose a letter"));
  await page.keyboard.press("Shift+KeyE");
  record("Modifier chord is rejected", (await page.locator("#hud-binding-status").textContent()).includes("without modifiers"));
  await page.keyboard.press("Escape");
  record("Escape cancels capture without closing settings", await page.locator("#hud-camera-dialog").evaluate((dialog) => dialog.open));
  await page.locator("#hud-bind-brake").click();
  await page.keyboard.press("Tab");
  record("Tab keeps normal focus navigation", await page.evaluate(() => document.activeElement?.id !== "hud-bind-brake"));
  await close();
  await page.keyboard.press("KeyR");
  await step(0);
  await page.keyboard.down("Space");
  const noOldAlias = await step(1);
  await page.keyboard.up("Space");
  record("Removed Space alias does not brake", noOldAlias.kart.brakeInput === 0);
  await page.keyboard.press("KeyM");
  const mode = await step(0);
  record("Practice mode changes normally", mode.mode === "Corner Drill");
  await page.keyboard.down("KeyF");
  const afterMode = await step(1);
  await page.keyboard.up("KeyF");
  record("F survives reset and mode change", afterMode.kart.brakeInput > 0 && afterMode.kart.brakeInput < 0.1);
  await open();
  await bind("accelerator", "KeyE");
  await bind("left", "KeyJ");
  await bind("right", "KeyK");
  await close();
  await page.keyboard.down("KeyE");
  await page.keyboard.down("KeyJ");
  const left = await step(6);
  await page.keyboard.up("KeyE");
  await page.keyboard.up("KeyJ");
  record("Remapped accelerator and left steer drive", left.kart.throttleInput > 0 && left.kart.steerAngleRad < 0);
  await page.keyboard.down("KeyK");
  const right = await step(24);
  await page.keyboard.up("KeyK");
  record("Remapped right steers", right.kart.steerAngleRad > 0);
  await step(1, { gamepad: { throttle: 0, brake: 0, steer: 0 } });
  const pad = await step(1, { gamepad: { throttle: 0.6, brake: 0, steer: 0.3 } });
  record("Gamepad remains independent", pad.kart.throttleInput === 0.6 && pad.kart.steerAngleRad > 0);
  await page.keyboard.down("KeyF");
  await step(1);
  await open();
  await bind("brake", "KeyB");
  await close();
  await page.evaluate(() => window.dispatchEvent(new KeyboardEvent("keydown", { code: "KeyF", repeat: true, bubbles: true, cancelable: true })));
  const cleared = await step(1);
  await page.keyboard.up("KeyF");
  record("Changing bindings clears held old input", cleared.kart.brakeInput === 0);
  await page.evaluate(() => window.dispatchEvent(new KeyboardEvent("keydown", { code: "KeyB", repeat: true, bubbles: true, cancelable: true })));
  record("Repeat of captured new key needs a fresh press", (await step(1)).kart.brakeInput === 0);
  await page.locator("#hud-btn-data").click();
  await page.locator("#hud-data-textarea").fill("typing keys: f e j k");
  const beforeTyping = await step(0);
  await page.locator("#hud-data-textarea").press("KeyB");
  const typed = await page.locator("#hud-data-textarea").inputValue();
  const afterTyping = await step(120);
  record("Typing does not drive", beforeTyping.kart.position.x === afterTyping.kart.position.x && typed.endsWith("b"));
  await page.locator('#hud-data-dialog button[type="submit"]').click();
  await page.waitForFunction(() => document.activeElement === document.body);
  const chord = await page.evaluate(() => {
    const event = new KeyboardEvent("keydown", { code: "KeyE", ctrlKey: true, bubbles: true, cancelable: true });
    window.dispatchEvent(event);
    return { defaultPrevented: event.defaultPrevented, snapshot: window.controlsHarness.step(1) };
  });
  record("Browser modifier shortcut is not prevented", !chord.defaultPrevented && chord.snapshot.kart.throttleInput === 0);
  await open();
  await page.locator("#hud-bind-defaults").click();
  record("Default accelerator aliases restored", await page.locator("#hud-bind-accelerator").textContent() === "W / Up");
  record("Default Brake/Reverse aliases restored", await page.locator("#hud-bind-brake").textContent() === "Space / S / Down");
  record("Default steer aliases restored", await page.locator("#hud-bind-left").textContent() === "A / Left" && await page.locator("#hud-bind-right").textContent() === "D / Right");
  await page.screenshot({ path: join(outputDirectory, "controls-settings.png") });
  await close();
  await page.keyboard.press("KeyR");
  const shiftChord = await page.evaluate(() => {
    const event = new KeyboardEvent("keydown", { code: "Space", shiftKey: true, bubbles: true, cancelable: true });
    window.dispatchEvent(event);
    return { defaultPrevented: event.defaultPrevented, snapshot: window.controlsHarness.step(1) };
  });
  record("Shift chord retains normal browser behavior", !shiftChord.defaultPrevented && shiftChord.snapshot.kart.brakeInput === 0);
  await page.keyboard.up("Space");
  await page.keyboard.down("Space");
  await page.keyboard.down("KeyS");
  await step(900);
  await page.keyboard.up("Space");
  const aliasHeld = await step(120);
  record("Releasing one alias does not release another or engage reverse", aliasHeld.kart.speedMps === 0 && aliasHeld.kart.driveDirection === "Forward");
  await page.keyboard.up("KeyS");
  await step(1);
  await page.keyboard.down("Space");
  const reverse = await step(180);
  await page.keyboard.up("Space");
  record("Default Space still engages deliberate reverse", reverse.kart.speedMps < 0 && Math.abs(reverse.kart.speedKph - 8) < 1e-9);
  await page.goto(`${baseUrl}/tests/browser/dialog-focus.html`);
  await page.locator("#run").click();
  await page.waitForFunction(() => document.querySelector("#result").textContent.startsWith("{"));
  const dialogResult = JSON.parse(await page.locator("#result").textContent());
  record("Existing dialog and results focus checks remain green", dialogResult.passed);
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.goto(baseUrl);
  await page.locator("#hud-btn-camera-settings").click();
  await page.locator("#hud-bind-brake").click();
  await page.keyboard.press("KeyF");
  await page.screenshot({ path: join(outputDirectory, "controls-main-settings.png") });
  await page.locator('#hud-camera-dialog button[type="submit"]').click();
  await page.waitForFunction(() => document.activeElement === document.body);
  await page.keyboard.down("KeyF");
  await page.waitForFunction(() => parseFloat(document.querySelector("#hud-brake-bar").style.width) > 0);
  record("Production bootstrap uses remapped key", parseFloat(await page.locator("#hud-brake-bar").evaluate((element) => element.style.width)) > 0);
  await page.keyboard.up("KeyF");
  await page.waitForFunction(() => parseFloat(document.querySelector("#hud-brake-bar").style.width) === 0);
  await page.locator("#hud-btn-reset").click();
  record("Production reset retains active hint", (await page.locator("#hud-driving-hint").textContent()).includes("Brake/Reverse: F"));
  record("No browser errors", errors.length === 0);
  const result = { passed: true, checks, firstPressure: braking.kart.brakeInput, reverseSpeedKph: reverse.kart.speedKph, errors };
  await writeFile(join(outputDirectory, "controls-browser-result.json"), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally {
  await browser.close();
}
