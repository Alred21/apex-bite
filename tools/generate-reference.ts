import { writeFileSync } from 'node:fs';
import { buildK1TorontoCircuit } from '../src/simulation/circuit';
import { searchReferenceLap, referenceRecipeSignature, type ReferenceRecipe } from '../src/simulation/reference-lap';
if (process.argv.includes('--geometry-experiment')) {
  await import('./experiment-reference-geometry');
} else if (process.argv.includes('--control-experiment')) {
  await import('./experiment-reference-controls');
} else {
  const circuit = buildK1TorontoCircuit();
  const start = performance.now();
  const { reference, proposal } = searchReferenceLap(circuit);
  const recipe: ReferenceRecipe = { signature: referenceRecipeSignature(circuit), name: proposal.name, positions: proposal.positions, lapSeconds: reference.lapSeconds, evidence: reference.evidence };
  writeFileSync('src/simulation/reference-recipe.ts', '// Generated by npm run reference:generate. Do not edit by hand.\nimport type { ReferenceRecipe } from \'./reference-lap\';\nexport const REFERENCE_RECIPE: ReferenceRecipe = ' + JSON.stringify(recipe) + ';\n');
  console.log(JSON.stringify({ seconds: (performance.now() - start) / 1000, name: reference.name, lapSeconds: reference.lapSeconds, candidates: reference.evidence.length, feasible: reference.evidence.filter((candidate) => candidate.feasible).length, closure: reference.closure }, null, 2));
}
